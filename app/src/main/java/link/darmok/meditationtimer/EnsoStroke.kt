    private val path: Path by lazy {
        val stroke = PathParser().parsePathString(PATH).toPath()
        val hairs = PathParser().parsePathString(HEAD_HAIRS).toPath()
        Path.combine(PathOperation.Union, stroke, hairs)
    }

    private fun at(table: FloatArray, degrees: Float): Float {
        val pos = (degrees % 360f + 360f) % 360f / STEP
        val i = pos.toInt() % table.size
        val t = pos - pos.toInt()
        return table[i] * (1 - t) + table[(i + 1) % table.size] * t
    }

    /**
     * Draws the faint whole ensō in [track], then the part filled so far in [ink]. The artwork
     * is mirrored and turned so its thin tail starts at 12 o'clock and the fill runs clockwise
     * from the tail round to the heavy head.
     */
    fun DrawScope.drawEnso(fraction: Float, ink: Color, track: Color) {
        val scale = size.minDimension / 2 / MAX_RADIUS * OVERSIZE
        val middle = Offset(CENTER_X, CENTER_Y)
        withTransform({
            translate(center.x - CENTER_X * scale, center.y - CENTER_Y * scale)
            scale(scale, scale, pivot = Offset.Zero)
            rotate(GAP, pivot = middle)
            scale(-1f, 1f, pivot = middle)
        }) {
            drawPath(path, track)
            if (fraction <= 0f) return@withTransform
            if (fraction >= 1f) {
                drawPath(path, ink)
                return@withTransform
            }

            // Everything below is in the artwork's own, untransformed coordinates, where the
            // fill runs anticlockwise from the gap. Uncovered so far: a wedge from the gap to
            // the current position, finished with a circle as wide as the stroke there, so the
            // leading edge is a smooth semicircle with no seam.
            val tip = GAP - fraction * SWEEP
            val inner = at(INNER, tip)
            val outer = at(OUTER, tip)
            val mid = (inner + outer) / 2
            val rad = Math.toRadians(tip.toDouble())
            val tipCenter = Offset(CENTER_X + mid * sin(rad).toFloat(), CENTER_Y - mid * cos(rad).toFloat())
            val wedge = Path().apply {
                moveTo(CENTER_X, CENTER_Y)
                arcTo(
                    Rect(center = middle, radius = MAX_RADIUS * 1.5f),
                    startAngleDegrees = GAP - 90f, sweepAngleDegrees = tip - GAP, forceMoveTo = false,
                )
                close()
            }
            val cap = Path().apply { addOval(Rect(center = tipCenter, radius = (outer - inner) / 2 + 0.5f)) }
            clipPath(Path.combine(PathOperation.Union, wedge, cap)) { drawPath(path, ink) }
        }
    }

    
